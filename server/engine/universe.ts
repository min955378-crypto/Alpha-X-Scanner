export interface UniverseEntry {
  symbol: string;
  baseAsset: string;
  isMonitoringTag: boolean;
}

/** Deterministic, de-duplicated, leveraged-token-free universe. */
export function buildUniverse(): UniverseEntry[] {
  const monitoring = new Set(MONITORING_TAG_SYMBOLS);
  const seen = new Set<string>();
  const out: UniverseEntry[] = [];

  for (const base of RAW.split(/\s+/)) {
    const b = base.trim().toUpperCase();
    if (!b || seen.has(b)) continue;
    if (isLeveragedToken(b)) continue;
    seen.add(b);
    out.push({ symbol: `${b}USDT`, baseAsset: b, isMonitoringTag: monitoring.has(b) });
  }
  return out;
}

/** §1.2  Monitoring-tag detection also accepts the Admin override. */
export function monitoringTagSet(): Set<string> {
  return new Set(MONITORING_TAG_SYMBOLS);
}
